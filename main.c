static unsigned char sendbuf[2000] = { 0 }, recvbuf[2000] = { 0 };
static struct IEEE8021XPacket *sendbuf_ieee8021x = (struct IEEE8021XPacket *)sendbuf;
static struct IEEE8021XPacket *recvbuf_ieee8021x = (struct IEEE8021XPacket *)recvbuf;
static struct EAPPacket *sendbuf_eap = (struct EAPPacket *) &sendbuf[sizeof(struct IEEE8021XPacket)];
static struct EAPPacket *recvbuf_eap = (struct EAPPacket *) &recvbuf[sizeof(struct IEEE8021XPacket)];
static unsigned sendbuflen = 0, recvbuflen = 0;
static const unsigned sendbufsiz=sizeof(sendbuf),recvbufsiz=sizeof(recvbuf);
// *INDENT-ON*

int main(int argc, char *argv[])
{
    struct sockaddr_ll send_addr;
    send_addr.sll_family = AF_PACKET;
    send_addr.sll_protocol = htons(ETH_P_PAE);
    send_addr.sll_addr[0] = 0x01;
    send_addr.sll_addr[1] = 0xD0;
    send_addr.sll_addr[2] = 0xF8;
    send_addr.sll_addr[3] = 0x00;
    send_addr.sll_addr[4] = 0x00;
    send_addr.sll_addr[5] = 0x03;
    send_addr.sll_halen = 6;

    for (
        int opt = getopt(argc, argv, "u:p:s:i:");
        opt != -1;
        opt = getopt(argc, argv, "u:p:s:i:")
    )
        switch (opt) {
            case 'u':
                username = optarg;
                break;

            case 'p':
                password = optarg;
                break;

            case 's':
                service_name = optarg;
                break;

            case 'i':
                net_interface_name = optarg;
                break;

            case '?':
                return EXIT_FAILURE;
        }

    if (!username || !password || !net_interface_name) {
        fputs("username, password and net interface name are required\n", stderr);
        return EXIT_FAILURE;
    }

    // we assume the env has already done dhcp
    int ether_socket = socket(AF_PACKET, SOCK_DGRAM, htons(ETH_P_PAE));

    if (ether_socket == -1) {
        perror("could not create ether socket");
        return EXIT_FAILURE;
    }

    if ((send_addr.sll_ifindex = if_nametoindex(net_interface_name)) == -1) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    if (
        bind(ether_socket, (const struct sockaddr *)&send_addr, sizeof(send_addr)) == -1
    ) {
        perror("could not bind to interface");
        close(ether_socket);
        return EXIT_FAILURE;
    }

    /////////////////////////////////////////////////
    // stage 1: send eapol start pkg
    /////////////////////////////////////////////////
    puts("sending eapol start pkg...");
    sendbuflen = sizeof(struct IEEE8021XPacketHeader);
    sendbuf_ieee8021x->header.version = 1;
    sendbuf_ieee8021x->header.type = IEEE8021X_EAPOL_START;
    sendbuf_ieee8021x->header.length = htons(0);

    if (append_private_properties(sendbuf, sendbufsiz, &sendbuflen, 0,
                                  false) == -1) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    if (send_ether_packet(ether_socket, &send_addr, sendbuf, sendbuflen) < 0) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    for (unsigned i = 0; i < 3; i++) {
        int l = recv_ether_packet_with_timeout(
                    ether_socket,
                    &send_addr,
                    recvbuf,
                    recvbufsiz,
                    3
                );

        if (l < 0)
            continue;

        if (
            l < (sizeof(struct IEEE8021XPacketHeader) + sizeof(struct EAPPacketHeader))
        ) {
            fputs("short packet read\n", stderr);
            continue;
        }

        recvbuflen = l;
        break;
    }

    if (!recvbuflen) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    puts("got reply");

    if (recvbuf_ieee8021x->header.type != IEEE8021X_EAP_PACKET) {
        fputs("reply packet type is not eap packet\n", stderr);
        return EXIT_FAILURE;
    }

    switch (recvbuf_eap->header.status_code) {
        case EAP_CODE_FAILURE:
            assert(ntohl(*(uint32_t *)recvbuf_eap->without_type.extra) == 0x1311);
            fputs("error from remote: ", stderr);
            // TODO convert to utf8
            fwrite(
                &recvbuf_eap->without_type.extra[6],
                1,
                ntohs(*(uint16_t *)&recvbuf_eap->without_type.extra[4]),
                stderr
            );
            fputc('\n', stderr);
            return EXIT_FAILURE;

        case EAP_CODE_REQUEST:
            break;

        default:
            fputs("remote returned unknown status code\n", stderr);
            return EXIT_FAILURE;
    }

    switch (recvbuf_eap->with_type.type) {
        case EAP_IDENTITY:
            break;

        case EAP_NOTIFICATION:
            fputs("error from remote: ", stderr);
            fwrite(recvbuf_eap->with_type.extra, 1, ntohs(recvbuf_eap->header.length) - 5,
                   stderr);
            fputc('\n', stderr);
            return EXIT_FAILURE;

        default:
            sendbuflen = (
                             sizeof(struct IEEE8021XPacketHeader) +
                             sizeof(struct EAPPacketHeader) +
                             1
                         );
            sendbuf_ieee8021x->header.version = 1;
            sendbuf_ieee8021x->header.type = IEEE8021X_EAP_PACKET;
            sendbuf_ieee8021x->header.length = htons(5);
            sendbuf_eap->header.status_code = EAP_CODE_RESPONSE;
            sendbuf_eap->header.id = recvbuf_eap->header.id;
            sendbuf_eap->header.length = htons(5);
            sendbuf_eap->with_type.type = EAP_NAK;

            if (
                append_private_properties(sendbuf, sendbufsiz, &sendbuflen, 0, false) == -1
            ) {
                close(ether_socket);
                return EXIT_FAILURE;
            }

            send_ether_packet(
                ether_socket,
                &send_addr,
                sendbuf,
                sendbuflen
            );
            return EXIT_FAILURE;
    }

    /////////////////////////////////////////////////
    // stage 2: send eap identity pkg
    /////////////////////////////////////////////////
    sendbuflen = (
                     sizeof(struct IEEE8021XPacketHeader) +
                     sizeof(struct EAPPacketHeader) +
                     1
                 );
    sendbuf_ieee8021x->header.version = 1;
    sendbuf_ieee8021x->header.type = IEEE8021X_EAP_PACKET;
    sendbuf_ieee8021x->header.length = htons(5 + strlen(username));
    sendbuf_eap->header.status_code = EAP_CODE_RESPONSE;
    sendbuf_eap->header.id = recvbuf_eap->header.id;
    sendbuf_eap->header.length = htons(5 + strlen(username));
    sendbuf_eap->with_type.type = EAP_IDENTITY;
    strncpy(sendbuf_eap->with_type.extra, username, sendbufsiz - sendbuflen - 1);
    sendbuflen += MIN(sendbufsiz - sendbuflen - 1, strlen(username));

    if (
        append_private_properties(sendbuf, sendbufsiz, &sendbuflen, 0, false) == -1
    ) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    puts("sending eap identity pkg...");

    if (send_ether_packet(ether_socket, &send_addr, sendbuf, sendbuflen) < 0) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    for (unsigned i = 0; i < 10; i++) {
        int l = recv_ether_packet_with_timeout(
                    ether_socket,
                    &send_addr,
                    recvbuf,
                    recvbufsiz,
                    45
                );

        if (l < 0)
            continue;

        if (
            l < (sizeof(struct IEEE8021XPacketHeader) + sizeof(struct EAPPacketHeader))
        ) {
            fputs("short packet read\n", stderr);
            continue;
        }

        recvbuflen = l;
        break;
    }

    if (!recvbuflen) {
        close(ether_socket);
        return EXIT_FAILURE;
    }

    puts("got reply");

    if (recvbuf_ieee8021x->header.type != IEEE8021X_EAP_PACKET) {
        fputs("reply packet type is not eap packet\n", stderr);
        return EXIT_FAILURE;
    }

    switch (recvbuf_eap->header.status_code) {
        case EAP_CODE_FAILURE:
            assert(ntohl(*(uint32_t *)recvbuf_eap->without_type.extra) == 0x1311);
            fputs("error from remote: ", stderr);
            // TODO convert to utf8
            fwrite(
                &recvbuf_eap->without_type.extra[6],
                1,
                ntohs(*(uint16_t *)&recvbuf_eap->without_type.extra[4]),
                stderr
            );
            fputc('\n', stderr);
            return EXIT_FAILURE;

        case EAP_CODE_REQUEST:
            break;

        default:
            fputs("remote returned unknown status code\n", stderr);
            return EXIT_FAILURE;
    }

    switch (recvbuf_eap->with_type.type) {
        case EAP_MD5_CHALLENGE:
            break;

        case EAP_NOTIFICATION:
            fputs("error from remote: ", stderr);
            fwrite(recvbuf_eap->with_type.extra, 1, ntohs(recvbuf_eap->header.length) - 5,
                   stderr);
            fputc('\n', stderr);
            return EXIT_FAILURE;

        default:
            sendbuflen = (
                             sizeof(struct IEEE8021XPacketHeader) +
                             sizeof(struct EAPPacketHeader) +
                             1
                         );
            sendbuf_ieee8021x->header.version = 1;
            sendbuf_ieee8021x->header.type = IEEE8021X_EAP_PACKET;
            sendbuf_ieee8021x->header.length = htons(5);
            sendbuf_eap->header.status_code = EAP_CODE_RESPONSE;
            sendbuf_eap->header.id = recvbuf_eap->header.id;
            sendbuf_eap->header.length = htons(5);
            sendbuf_eap->with_type.type = EAP_NAK;

            if (
                append_private_properties(sendbuf, sendbufsiz, &sendbuflen, 0, false) == -1
            ) {
                close(ether_socket);
                return EXIT_FAILURE;
            }

            send_ether_packet(
                ether_socket,
                &send_addr,
                sendbuf,
                sendbuflen
            );
            return EXIT_FAILURE;
    }

    assert(recvbuf_eap->with_type.extra[0] == 16);
    memcpy(
        md5_challenge,
        &recvbuf_eap->with_type.extra[1],
        recvbuf_eap->with_type.extra[0]
    );

    if (ntohs(recvbuf_eap->header.length) - 22) {
        for (unsigned i = 17; i < ntohs(recvbuf_eap->header.length) - 5;) {
            assert(ntohl(*(uint32_t *)&recvbuf_eap->with_type.extra[i]) == 0x1311);
            i += 4;

            switch (recvbuf_eap->with_type.extra[i]) {
                case 0x2E:
                    assert(recvbuf_eap->with_type.extra[i + 1] == 3);
                    should_encrypt_password_in_md5_response = recvbuf_eap->with_type.extra[i + 2];
                    break;

                case 0x66: {
                        assert(recvbuf_eap->with_type.extra[i + 1] >= 2);
                        unsigned service_list_length = recvbuf_eap->with_type.extra[i + 1] - 2;
                        puts("service list:");
                        fputs("1. ", stdout);

                        for (unsigned p = 0, l = 1; p < service_list_length; p++) {
                            if (recvbuf_eap->with_type.extra[i + p] == '@') {
                                printf("%u: ", ++l);
                                continue;
                            }

                            putchar(recvbuf_eap->with_type.extra[i + p]);
                        }

                        putchar('\n');
                        break;
                    }
            }

            i += recvbuf_eap->with_type.extra[i + 1];
        }
    }

    /////////////////////////////////////////////////
    // stage 3: send md5 challenge reply
    /////////////////////////////////////////////////
    sendbuflen = (
                     sizeof(struct IEEE8021XPacketHeader) +
                     sizeof(struct EAPPacketHeader) +
                     1
                 );
    sendbuf_ieee8021x->header.version = 1;
    sendbuf_ieee8021x->header.type = IEEE8021X_EAP_PACKET;
    sendbuf_ieee8021x->header.length = htons(22 + strlen(username));
    sendbuf_eap->header.status_code = EAP_CODE_RESPONSE;
    sendbuf_eap->header.id = recvbuf_eap->header.id;
    sendbuf_eap->header.length = htons(22 + strlen(username));
    sendbuf_eap->with_type.type = EAP_MD5_CHALLENGE;
    sendbuf_eap->with_type.extra[0] = 16;
    sendbuflen++;
    {
        md5_ctx ctx;
        rhash_md5_init(&ctx);
        rhash_md5_update(&ctx, &recvbuf_eap->header.id, 1);
        rhash_md5_update(&ctx, password, strlen(password));
        rhash_md5_update(&ctx, md5_challenge, sizeof(md5_challenge));
        rhash_md5_final(&ctx, &sendbuf_eap->with_type.extra[1]);
        sendbuflen += 16;
    }
    strncpy(sendbuf_eap->with_type.extra, username, sendbufsiz - sendbuflen);
    sendbuflen += MIN(sendbufsiz - sendbuflen, strlen(username));
    return EXIT_SUCCESS;
}
